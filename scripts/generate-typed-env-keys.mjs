#!/usr/bin/env node

import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ENV_KEY_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const TYPE_NAME_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const PARSE_ENV_FIELDS = new Set([
  "command_env",
  "positionals_env",
  "unknown_options_env",
  "errors_env",
]);

function stripComment(line) {
  let quoted = false;
  let escaped = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (escaped) {
      escaped = false;
      continue;
    }
    if (ch === "\\" && quoted) {
      escaped = true;
      continue;
    }
    if (ch === '"') {
      quoted = !quoted;
      continue;
    }
    if (ch === "#" && !quoted) {
      return line.slice(0, i);
    }
  }
  return line;
}

function parseTomlString(raw, context) {
  const value = raw.trim();
  if (!value.startsWith('"')) {
    throw new Error(`${context} must be a TOML basic string`);
  }
  let escaped = false;
  for (let i = 1; i < value.length; i += 1) {
    const ch = value[i];
    if (escaped) {
      escaped = false;
      continue;
    }
    if (ch === "\\") {
      escaped = true;
      continue;
    }
    if (ch === '"') {
      const literal = value.slice(0, i + 1);
      const remainder = value.slice(i + 1).trim();
      if (remainder !== "") {
        throw new Error(`${context} has trailing content`);
      }
      return JSON.parse(literal);
    }
  }
  throw new Error(`${context} is unterminated`);
}

function declaresParserEnv(section, key) {
  if (section === "parse") {
    return PARSE_ENV_FIELDS.has(key);
  }
  if (key !== "env") {
    return false;
  }
  return (
    section.startsWith("flags.") ||
    section.startsWith("global.flags.") ||
    section.startsWith("commands.")
  );
}

export function parseContract(text) {
  let section = "";
  let typeName;
  const keys = new Set();

  for (const [index, rawLine] of text.split(/\r?\n/).entries()) {
    const lineNumber = index + 1;
    const line = stripComment(rawLine).trim();
    if (!line) {
      continue;
    }
    if (line.startsWith("[") && line.endsWith("]")) {
      section = line.slice(1, -1).trim();
      continue;
    }

    const equals = line.indexOf("=");
    if (equals < 1) {
      continue;
    }
    const key = line.slice(0, equals).trim();
    const rawValue = line.slice(equals + 1).trim();

    if (section === "identity" && key === "type_name") {
      typeName = parseTomlString(rawValue, `line ${lineNumber}: identity.type_name`);
      continue;
    }

    if (!declaresParserEnv(section, key)) {
      continue;
    }

    const envKey = parseTomlString(rawValue, `line ${lineNumber}: ${section}.${key}`);
    if (!envKey) {
      continue;
    }
    if (!ENV_KEY_RE.test(envKey)) {
      throw new Error(`line ${lineNumber}: invalid environment key ${JSON.stringify(envKey)}`);
    }
    keys.add(envKey);
  }

  return { typeName, keys: [...keys].sort() };
}

function pascalCaseEnvKey(key) {
  const pieces = key.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const value = pieces
    .map((piece) => piece[0].toUpperCase() + piece.slice(1).toLowerCase())
    .join("");
  return value && /^[A-Za-z_]/.test(value) ? value : `Env${value || "Key"}`;
}

function lowerCamelEnvKey(key) {
  const pascal = pascalCaseEnvKey(key);
  return pascal[0].toLowerCase() + pascal.slice(1);
}

function assertNoIdentifierCollisions(keys, project) {
  const seen = new Map();
  for (const key of keys) {
    const identifier = project(key);
    const previous = seen.get(identifier);
    if (previous && previous !== key) {
      throw new Error(`environment keys ${previous} and ${key} both generate identifier ${identifier}`);
    }
    seen.set(identifier, key);
  }
}

function renderTypeScript(typeName, keys) {
  const keyType = `${typeName}Key`;
  const mapType = `${typeName}Map`;
  const entries = keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(key)},`).join("\n");
  return `/* Generated by flags2env from .cli-flags.toml. Do not edit. */\n\nexport const ${keyType} = {\n${entries}\n} as const;\n\nexport type ${keyType} = typeof ${keyType}[keyof typeof ${keyType}];\nexport type ${mapType} = Readonly<Partial<Record<${keyType}, string>>>;\n\nexport function get${typeName}Value(env: ${mapType}, key: ${keyType}): string | undefined {\n  return env[key];\n}\n\nexport function define${mapType}<T extends ${mapType}>(\n  env: T & Record<Exclude<keyof T, ${keyType}>, never>,\n): T {\n  return env;\n}\n`;
}

function renderRust(typeName, keys) {
  const keyType = `${typeName}Key`;
  const mapType = `${typeName}Map`;
  assertNoIdentifierCollisions(keys, pascalCaseEnvKey);
  const variants = keys.map((key) => `    ${pascalCaseEnvKey(key)},`).join("\n");
  const matches = keys
    .map((key) => `            Self::${pascalCaseEnvKey(key)} => ${JSON.stringify(key)},`)
    .join("\n");
  return `// Generated by flags2env from .cli-flags.toml. Do not edit.\n\nuse std::collections::BTreeMap;\n\n#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\npub enum ${keyType} {\n${variants}\n}\n\nimpl ${keyType} {\n    #[must_use]\n    pub const fn as_str(self) -> &'static str {\n        match self {\n${matches}\n        }\n    }\n}\n\npub type ${mapType} = BTreeMap<${keyType}, String>;\n`;
}

function renderGleam(typeName, keys) {
  const keyType = `${typeName}Key`;
  const mapType = `${typeName}Map`;
  const functions = keys
    .map((key) => `pub fn env_${lowerCamelEnvKey(key).replace(/[A-Z]/g, (ch) => `_${ch.toLowerCase()}`)}() -> ${keyType} {\n  ${keyType}(${JSON.stringify(key)})\n}\n`)
    .join("\n");
  return `// Generated by flags2env from .cli-flags.toml. Do not edit.\n\nimport gleam/dict.{type Dict}\n\npub opaque type ${keyType} {\n  ${keyType}(String)\n}\n\npub type ${mapType} = Dict(${keyType}, String)\n\npub fn env_key_name(key: ${keyType}) -> String {\n  let ${keyType}(name) = key\n  name\n}\n\n${functions}`;
}

function renderDart(typeName, keys) {
  const keyType = `${typeName}Key`;
  const mapType = `${typeName}Map`;
  assertNoIdentifierCollisions(keys, lowerCamelEnvKey);
  const fields = keys
    .map((key) => `  static const env${pascalCaseEnvKey(key)} = ${keyType}._(${JSON.stringify(key)});`)
    .join("\n");
  return `// Generated by flags2env from .cli-flags.toml. Do not edit.\n\nfinal class ${keyType} {\n  final String wireName;\n  const ${keyType}._(this.wireName);\n\n${fields}\n}\n\ntypedef ${mapType} = Map<${keyType}, String>;\n\nString? get${typeName}Value(${mapType} env, ${keyType} key) => env[key];\n`;
}

export function renderAll(contract, explicitTypeName) {
  const typeName = explicitTypeName || contract.typeName || "CliConfig";
  if (!TYPE_NAME_RE.test(typeName)) {
    throw new Error(`invalid generated type name ${JSON.stringify(typeName)}`);
  }
  return {
    "env_keys.ts": renderTypeScript(typeName, contract.keys),
    "env_keys.rs": renderRust(typeName, contract.keys),
    "env_keys.gleam": renderGleam(typeName, contract.keys),
    "env_keys.dart": renderDart(typeName, contract.keys),
  };
}

function parseArgs(argv) {
  let config = ".cli-flags.toml";
  let outputDir = "generated/typed-env";
  let typeName;
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === "--config" || token === "-c") {
      config = argv[++i];
    } else if (token === "--output-dir" || token === "-o") {
      outputDir = argv[++i];
    } else if (token === "--name" || token === "-n") {
      typeName = argv[++i];
    } else if (!token.startsWith("-") && config === ".cli-flags.toml") {
      config = token;
    } else {
      throw new Error(`unknown argument ${token}`);
    }
  }
  return { config, outputDir, typeName };
}

export async function generateTypedEnvKeys({ config, outputDir, typeName }) {
  const source = await readFile(config, "utf8");
  const contract = parseContract(source);
  const rendered = renderAll(contract, typeName);
  await mkdir(outputDir, { recursive: true });
  await writeFile(
    join(outputDir, "README.md"),
    `<!-- generated-policy: frozen -->\n\n# Typed environment keys\n\nGenerated from \`${basename(config)}\` by \`scripts/generate-typed-env-keys.mjs\`. Do not edit generated language files.\n`,
  );
  for (const [name, contents] of Object.entries(rendered)) {
    const path = join(outputDir, name);
    await writeFile(path, contents);
    await chmod(path, 0o444);
  }
  return { contract, outputDir: resolve(outputDir), files: Object.keys(rendered) };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (!options.config || !options.outputDir) {
    throw new Error("usage: node scripts/generate-typed-env-keys.mjs [config] [--name TypeName] [--output-dir generated/typed-env]");
  }
  const result = await generateTypedEnvKeys(options);
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(`flags2env typed-env generation failed: ${error.message}`);
    process.exitCode = 1;
  });
}
